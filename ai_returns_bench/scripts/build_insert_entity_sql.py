#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
DEFAULT_OUT = ROOT / "deltastream" / "02_load_seed_data.sql"

TOPIC_MAP = {
    "orders.jsonl": "aws_returns_orders",
    "shipments.jsonl": "aws_returns_shipments",
    "returns.jsonl": "aws_returns_returns",
    "refunds.jsonl": "aws_returns_refunds",
}


def _quote_sql_string(value: str) -> str:
    return value.replace("'", "''")


def _insert_stmt(topic: str, store: str, row: dict) -> str:
    payload = json.dumps(row, separators=(",", ":"), sort_keys=True)
    return (
        f"INSERT INTO ENTITY {topic} IN STORE {store} "
        f"VALUE('{_quote_sql_string(payload)}');"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--store", default="aws_returns_kafka_store")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args()

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append("-- Auto-generated by scripts/build_insert_entity_sql.py")
    lines.append("-- Loads deterministic benchmark seed data into Kafka topics via DeltaStream.")
    lines.append(f"-- Store: {args.store}")
    lines.append("")

    total = 0
    for file_name, topic in TOPIC_MAP.items():
        path = DATA_DIR / file_name
        if not path.exists():
            raise SystemExit(f"missing {path}; run scripts/generate_seed_data.py first")

        rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
        lines.append(f"-- {topic}: {len(rows)} rows")
        for row in rows:
            lines.append(_insert_stmt(topic, args.store, row))
        lines.append("")
        total += len(rows)

    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path}")
    print(f"total insert statements: {total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
